import type { LLMProvider } from "./llm";
import { extractFunctionsFromText } from "./parser";
import { generateTestCode } from "./generator";

// An error whose message is safe to show to the visitor
export class UserError extends Error {}

const MAX_FUNCTIONS = 4; // keeps requests fast and protects the free AI limit

const HEADER = `// Generated by TestGen. Review these tests before you rely on them!\n// 1. Put your functions in a file and export them:  export function name() { ... }\n// 2. Change "./your-file" below to that file's real path.\n// 3. Run the tests with:  npx vitest run\n`;

// Build the complete test file from function names and their describe blocks
function buildTestFile(fnNames: string[], describeBlocks: string[]): string {
  const importList = fnNames.join(", ");
  // The describe blocks should already include `import { describe, it, expect, vi } from "vitest"`.
  // Deduplicate that import and put one at the top, then add the function import.
  const blocksWithoutImport = describeBlocks.map((b) =>
    b.replace(/^import\s+\{[^}]*\}\s+from\s+"vitest";\s*\n?/m, "").trim()
  );

  return (
    `import { describe, it, expect, vi } from "vitest";\n` +
    `import { ${importList} } from "./your-file";\n\n` +
    blocksWithoutImport.join("\n\n") +
    "\n"
  );
}

// Extract test case metadata from generated code via simple regex
// Category is inferred from the bracket prefix: [happy], [edge], [negative]
function extractCasesFromCode(
  fnName: string,
  code: string
): Array<{ fn: string; name: string; category: string }> {
  const cases: Array<{ fn: string; name: string; category: string }> = [];
  // Match: it("[category] name", ...) or it('[category] name', ...)
  const itPattern = /\bit\s*\(\s*["'`]\[?(\w+)?\]?\s*(.*?)["'`]/g;
  let m: RegExpExecArray | null;
  while ((m = itPattern.exec(code)) !== null) {
    const bracket = m[1] ?? "happy";
    const name = m[2]?.trim() ?? "test";
    const cat = bracket.toLowerCase();
    const category = cat === "edge" ? "edge" : cat === "negative" ? "negative" : "happy";
    cases.push({ fn: fnName, name, category });
  }
  return cases;
}

export async function generateFromCode(code: string, llm: LLMProvider) {
  let functions;
  try {
    functions = extractFunctionsFromText(code);
  } catch {
    throw new UserError("Could not read that code. Check that it is valid JavaScript or TypeScript.");
  }
  if (functions.length === 0) {
    throw new UserError(
      "No functions found. Paste at least one function, for example: function add(a, b) { return a + b; }"
    );
  }

  const used = functions.slice(0, MAX_FUNCTIONS);
  const skipped = functions.length - used.length;

  // Ask the AI for all functions at the same time (faster than one by one)
  const settled = await Promise.allSettled(
    used.map(async (fn) => ({ fnName: fn.name, code: await generateTestCode(llm, fn) }))
  );

  const ok = settled.flatMap((s) => (s.status === "fulfilled" ? [s.value] : []));
  const failed = used.filter((_, i) => settled[i].status === "rejected").map((fn) => fn.name);

  if (ok.length === 0) throw new Error("The AI did not return valid tests for any function.");

  const fnNames = ok.map((r) => r.fnName);
  const describeBlocks = ok.map((r) => r.code);

  const testCode = HEADER + "\n" + buildTestFile(fnNames, describeBlocks);

  // Extract lightweight metadata from the generated code for the UI
  const cases = ok.flatMap((r) => extractCasesFromCode(r.fnName, r.code));
  const testCount = (testCode.match(/\bit\s*\(/g) ?? []).length;

  return {
    testCode,
    testCount,
    functions: ok.map((r) => ({
      name: r.fnName,
      count: (r.code.match(/\bit\s*\(/g) ?? []).length,
    })),
    skipped,
    failed,
    cases,
  };
}
